package com.example.data.remote

import com.example.data.model.ChatMessageEntity
import com.example.data.model.ChatSessionEntity
import com.example.model.ChatMessage
import com.example.model.MessageRole
import org.json.JSONArray
import org.json.JSONObject
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Serializes conversations into portable Markdown or JSON documents.
 */
object ConversationExporter {

    enum class Format(val extension: String, val mimeType: String) {
        MARKDOWN("md", "text/markdown"),
        JSON("json", "application/json")
    }

    fun fileName(title: String, format: Format): String {
        val base = title.trim()
            .ifBlank { "omnichat-export" }
            .replace(Regex("[^A-Za-z0-9._-]+"), "_")
            .trim('_')
            .ifBlank { "omnichat-export" }
            .take(48)
        return "$base.${format.extension}"
    }

    fun exportSession(
        session: ChatSessionEntity,
        messages: List<ChatMessageEntity>,
        format: Format
    ): String = when (format) {
        Format.MARKDOWN -> sessionToMarkdown(session, messages)
        Format.JSON -> sessionToJson(session, messages).toString(2)
    }

    fun exportAll(
        sessions: List<ChatSessionEntity>,
        messagesBySession: Map<String, List<ChatMessageEntity>>,
        format: Format
    ): String = when (format) {
        Format.MARKDOWN -> buildString {
            appendLine("# OmniChat Conversations")
            appendLine()
            appendLine("_Exported ${formatTimestamp(System.currentTimeMillis())}_")
            appendLine()
            appendLine("---")
            appendLine()
            sessions.forEachIndexed { index, session ->
                appendLine("## ${index + 1}. ${session.title.ifBlank { "New Chat" }}")
                appendLine()
                appendLine("_Model: ${session.modelId} • Updated ${formatTimestamp(session.updatedAt)}_")
                appendLine()
                messagesBySession[session.id].orEmpty().forEach { message ->
                    appendMessageMarkdown(this, message)
                }
                appendLine()
                appendLine("---")
                appendLine()
            }
        }

        Format.JSON -> JSONObject().apply {
            put("format", "omnichat-conversations")
            put("version", 1)
            put("exportedAt", System.currentTimeMillis())
            put("sessions", JSONArray().apply {
                sessions.forEach { session ->
                    put(
                        sessionToJson(session, messagesBySession[session.id].orEmpty())
                    )
                }
            })
        }.toString(2)
    }

    fun shareText(
        session: ChatSessionEntity,
        messages: List<ChatMessageEntity>
    ): String = buildString {
        appendLine("${session.title.ifBlank { "New Chat" }} — OmniChat")
        appendLine("Model: ${session.modelId}")
        appendLine()
        messages.forEach { message ->
            val speaker = when (message.role) {
                "user" -> "You"
                "system" -> "System"
                else -> "Assistant"
            }
            appendLine("$speaker:")
            appendLine(message.content)
            appendLine()
        }
        append("Shared from OmniChat")
    }

    fun shareText(
        title: String,
        modelId: String,
        messages: List<ChatMessage>
    ): String = buildString {
        appendLine("${title.ifBlank { "New Chat" }} — OmniChat")
        appendLine("Model: $modelId")
        appendLine()
        messages.forEach { message ->
            val speaker = when (message.role) {
                MessageRole.USER -> "You"
                MessageRole.SYSTEM -> "System"
                else -> "Assistant"
            }
            appendLine("$speaker:")
            appendLine(message.content)
            appendLine()
        }
        append("Shared from OmniChat")
    }

    private fun sessionToMarkdown(
        session: ChatSessionEntity,
        messages: List<ChatMessageEntity>
    ): String = buildString {
        appendLine("# ${session.title.ifBlank { "New Chat" }}")
        appendLine()
        appendLine("_Provider model: `${session.modelId}` — exported ${formatTimestamp(System.currentTimeMillis())}_")
        appendLine()
        appendLine("---")
        appendLine()
        messages.forEach { appendMessageMarkdown(this, it) }
        appendLine()
        append("_Generated by OmniChat_")
    }

    private fun appendMessageMarkdown(
        builder: StringBuilder,
        message: ChatMessageEntity
    ) {
        val speaker = when (message.role) {
            "user" -> "You"
            "system" -> "System"
            else -> "Assistant${if (message.modelId.isNotBlank()) " · ${message.modelId}" else ""}"
        }
        builder.appendLine("### $speaker")
        builder.appendLine()
        builder.appendLine("_${formatTimestamp(message.timestamp)}${if (message.isError) " • error" else ""}_")
        builder.appendLine()
        builder.appendLine(message.content)
        builder.appendLine()
    }

    private fun sessionToJson(
        session: ChatSessionEntity,
        messages: List<ChatMessageEntity>
    ): JSONObject = JSONObject().apply {
        put("id", session.id)
        put("title", session.title)
        put("providerId", session.providerId)
        put("modelId", session.modelId)
        put("createdAt", session.createdAt)
        put("updatedAt", session.updatedAt)
        put("messages", JSONArray().apply {
            messages.forEach { message ->
                put(JSONObject().apply {
                    put("id", message.id)
                    put("role", message.role)
                    put("content", message.content)
                    put("timestamp", message.timestamp)
                    put("providerId", message.providerId)
                    put("modelId", message.modelId)
                    put("attachmentsJson", message.attachmentsJson)
                    put("isError", message.isError)
                })
            }
        })
    }

    fun formatTimestamp(timestamp: Long): String =
        SimpleDateFormat("MMM d, yyyy • HH:mm", Locale.US).format(Date(timestamp))
}
